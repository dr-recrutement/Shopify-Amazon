export const CURRENCY_BY_CODE = Object.fromEntries(CURRENCIES.map((c) => [c.code, c]));

export function getCurrency(code) {
  return CURRENCY_BY_CODE[code] || null;
}

// Format an amount in a given currency (locale-aware). No fake conversions.
export function formatMoney(amount, currencyCode, locale = 'fr-FR') {
  const cur = getCurrency(currencyCode);
  try {
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency: currencyCode,
      minimumFractionDigits: cur ? cur.decimals : 2,
      maximumFractionDigits: cur ? cur.decimals : 2,
    }).format(Number(amount) || 0);
  } catch {
    const sym = cur ? cur.symbol : currencyCode || '';
    return `${sym}${Number(amount || 0).toFixed(cur ? cur.decimals : 2)}`;
  }
}

